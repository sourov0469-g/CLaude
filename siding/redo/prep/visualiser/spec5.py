def rule(a):
    r,g,b=a[...,0],a[...,1],a[...,2]; H,W=r.shape
    Y=0.2126*r+0.7152*g+0.0722*b; yy,xx=np.indices((H,W))
    sun=(r-b>=18)&(r>=g)&(g>=b)&(Y>=70)
    shade=(b-r>=8)&(Y>=45)&(Y<=140)&(xx<=520)&(yy>=290)
    return sun|shade
